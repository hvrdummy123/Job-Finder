def all_rows() -> list[CompanyRow]:
    """Merge lists, dedupe by lower(name), merge categories."""
    by_name: dict[str, CompanyRow] = {}
    for row in ENGINEERING + BLOCKCHAIN + FINTECH + REMOTE + PORTALS:
        key = row[0].lower()
        if key not in by_name:
            by_name[key] = row
            continue
        prev = by_name[key]
        cats = sorted(set(prev[3].split(",")) | set(row[3].split(",")))
        ats_type = prev[4] or row[4]
        ats_slug = prev[5] or row[5]
        by_name[key] = (prev[0], prev[1], prev[2], ",".join(cats), ats_type, ats_slug)
    return sorted(by_name.values(), key=lambda r: (r[3], r[0].lower()))


def category_counts(rows: list[CompanyRow]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for _, _, _, cats, _, _ in rows:
        for c in cats.split(","):
            c = c.strip()
            if c:
                counts[c] = counts.get(c, 0) + 1
    return counts
